-- HMS-T-02 | PostgreSQL 15 | SAD Section 4.1
-- Sensitive fields marked with * in SAD are stored as ciphertext (BYTEA).
BEGIN;

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('Receptionist','Doctor','Patient','Billing Officer','Administrator')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_attempts SMALLINT NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS patients (
    patient_id VARCHAR(12) PRIMARY KEY CHECK (patient_id ~ '^PID-[0-9]{8}$'),
    user_id BIGINT UNIQUE REFERENCES users(user_id) ON DELETE SET NULL,
    name BYTEA NOT NULL,
    dob BYTEA NOT NULL,
    gender VARCHAR(30) NOT NULL,
    phone BYTEA NOT NULL,
    address BYTEA NOT NULL,
    allergies BYTEA,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS patient_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id VARCHAR(12) NOT NULL REFERENCES patients(patient_id) ON DELETE RESTRICT,
    old_values BYTEA NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS doctors (
    doctor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE RESTRICT,
    specialty VARCHAR(120) NOT NULL,
    fee NUMERIC(12,2) NOT NULL CHECK (fee >= 0),
    working_hours JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS appointments (
    appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id VARCHAR(12) NOT NULL REFERENCES patients(patient_id) ON DELETE RESTRICT,
    doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id) ON DELETE RESTRICT,
    slot_start TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Confirmed'
        CHECK (status IN ('Confirmed','Cancelled','Completed','No-show')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (EXTRACT(SECOND FROM slot_start) = 0),
    CHECK (EXTRACT(MINUTE FROM slot_start)::INTEGER IN (0,30))
);

CREATE TABLE IF NOT EXISTS visits (
    visit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(appointment_id) ON DELETE RESTRICT,
    symptoms BYTEA NOT NULL,
    diagnosis BYTEA NOT NULL,
    notes BYTEA,
    visited_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS prescriptions (
    prescription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id BIGINT NOT NULL REFERENCES visits(visit_id) ON DELETE RESTRICT,
    item VARCHAR(200) NOT NULL,
    dosage VARCHAR(120) NOT NULL,
    frequency VARCHAR(120) NOT NULL,
    days INTEGER NOT NULL CHECK (days > 0),
    override_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS bills (
    bill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id BIGINT NOT NULL UNIQUE REFERENCES visits(visit_id) ON DELETE RESTRICT,
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    tax NUMERIC(12,2) NOT NULL CHECK (tax >= 0),
    total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Unpaid' CHECK (status IN ('Unpaid','Partially Paid','Paid','Cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (total = subtotal + tax)
);

CREATE TABLE IF NOT EXISTS bill_items (
    bill_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES bills(bill_id) ON DELETE RESTRICT,
    item VARCHAR(200) NOT NULL,
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0)
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES bills(bill_id) ON DELETE RESTRICT,
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    mode VARCHAR(30) NOT NULL CHECK (mode IN ('Cash','Card','UPI','Bank Transfer')),
    receipt_no VARCHAR(40) NOT NULL UNIQUE,
    paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audit_log (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    role VARCHAR(30) NOT NULL,
    action VARCHAR(120) NOT NULL,
    record_id VARCHAR(120),
    "timestamp" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source_ip INET
);

COMMIT;
